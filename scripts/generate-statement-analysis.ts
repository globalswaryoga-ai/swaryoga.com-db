function createPartySummary(type: 'DR' | 'CR') {
  const filtered = txList.filter((t) => t.type === type);
  const map = new Map<string, { totalAmount: number; count: number; dates: string[]; txs: Tx[] }>();

  for (const t of filtered) {
    const key = t.partyName;
    if (!map.has(key)) {
      map.set(key, { totalAmount: 0, count: 0, dates: [], txs: [] });
    }
    const entry = map.get(key)!;
    entry.totalAmount += t.amount;
    entry.count += 1;
    const dateOnly = t.txDate.split(' ')[0];
    if (!entry.dates.includes(dateOnly)) {
      entry.dates.push(dateOnly);
    }
    entry.txs.push(t);
  }

  const summary = Array.from(map.entries()).map(([name, data]) => ({
    name,
    totalAmount: Math.round(data.totalAmount * 100) / 100,
    count: data.count,
    dates: data.dates.join(', '),
    earliestDate: data.dates[0],
    latestDate: data.dates[data.dates.length - 1],
    txs: data.txs,
  }));

  summary.sort((a, b) => b.totalAmount - a.totalAmount);
  return summary;
}

