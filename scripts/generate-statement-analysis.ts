function extractPartyName(description: string, chqRef: string): string {
  const desc = description.trim();

  // 1. UPI patterns:
  if (desc.startsWith('UPI/')) {
    const parts = desc.split('/');
    if (parts.length >= 2 && parts[1].trim()) {
      return parts[1].trim();
    }
  }

  // 2. SentIMPS patterns:
  const impsMatch = desc.match(/^SentIMPS\d+([A-Za-z\s]+?)\//i);
  if (impsMatch && impsMatch[1]) {
    return impsMatch[1].trim();
  }
  const impsMatch2 = desc.match(/^SentIMPS\d+([A-Za-z\s]+)/i);
  if (impsMatch2 && impsMatch2[1]) {
    return impsMatch2[1].trim();
  }

  // 3. NEFT patterns:
  const neftMatch = desc.match(/^NEFT\s+[A-Z0-9]+\s+(.+?)(?:\s+[A-Z]{4}\d+)?$/i);
  if (neftMatch && neftMatch[1]) {
    let name = neftMatch[1].trim();
    name = name.replace(/\s+UTIB0?$/i, '').replace(/\s+UTI$/i, '').trim();
    return name;
  }

  // 4. PCI / PCD (Card / POS) patterns:
  if (desc.startsWith('PCI/') || desc.startsWith('PCD/')) {
    const parts = desc.split('/');
    if (parts.length >= 3 && parts[2].trim()) {
      return parts[2].trim();
    }
  }

  // 5. CASH DEPOSIT:
  const cashMatch = desc.match(/^Cash Deposit by (.+?) at/i);
  if (cashMatch && cashMatch[1]) {
    return `Cash Deposit - ${cashMatch[1].trim()}`;
  }

  // 6. Charges & Bank Fees:
  if (/^CHRG-POS TXN DECLINE FEE/i.test(desc) || /^REM-CHRG-POS TXN DECLINE FEE/i.test(desc)) {
    const parts = desc.split('/');
    const vendor = parts.length > 1 ? parts[parts.length - 1].trim() : '';
    return vendor ? `Bank Charge: Decline Fee (${vendor})` : 'Bank Charge: POS Decline Fee';
  }
  if (/AQB Non Maintenance/i.test(desc)) {
    return 'Bank Charge: AQB Non Maintenance';
  }
  if (/IMPS Transaction Dated/i.test(desc)) {
    return 'Bank Charge: IMPS Charges';
  }
  if (/DCC Fee/i.test(desc)) {
    return 'Bank Charge: DCC Fee';
  }
  if (/Debit Card Annual Fee/i.test(desc)) {
    return 'Bank Charge: Debit Card Annual Fee';
  }
  if (/Cash Deposit/i.test(desc)) {
    return 'Bank Charge: Cash Deposit Fee';
  }

  // 7. VISA REFUND:
  if (desc.startsWith('VISA-REFUND')) {
    const parts = desc.split('/');
    return parts[parts.length - 1]?.trim() ? `Refund: ${parts[parts.length - 1].trim()}` : 'VISA Refund';
  }

  // 8. REV:IMPS
  if (desc.startsWith('REV:IMPS')) {
    return 'Reversal: IMPS';
  }

  // 9. Recd:IMPS
  if (desc.startsWith('Recd:IMPS')) {
    const parts = desc.split('/');
    return parts.length >= 3 ? parts[2].trim() : 'IMPS Received';
  }

  // 10. UPI_CRADJ
  if (desc.startsWith('UPI_CRADJ')) {
    return 'UPI Credit Adjustment';
  }

  return desc;
}

function parseCSVLine(text: string): string[][] {
  const lines = text.split(/\r?\n/);
  const rows: string[][] = [];
  for (const line of lines) {
    if (!line.trim()) continue;
    const row: string[] = [];
    let insideQuotes = false;
    let entry = '';
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        if (insideQuotes && line[i + 1] === '"') {
          entry += '"';
          i++;
        } else {
          insideQuotes = !insideQuotes;
        }
      } else if (char === ',' && !insideQuotes) {
        row.push(entry.trim());
        entry = '';
      } else {
        entry += char;
      }
    }
    row.push(entry.trim());
    rows.push(row);
  }
  return rows;
}

