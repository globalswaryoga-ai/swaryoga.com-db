export function getLocalizedTithi(langCode: string, tithiNum: number, paksha: string, fallbackName: string): string {
  const code = (langCode || 'hi').toLowerCase();
  const dict = LOCALIZED_TITHIS[code];
  if (dict && dict[tithiNum]) {
    if (tithiNum === 15) {
      if (paksha.includes('Krishna')) {
        if (code === 'mr') return 'अमावास्या';
        if (code === 'gu') return 'અમાસ';
        if (code === 'kn') return 'ಅಮಾವಾಸ್ಯೆ';
        if (code === 'te') return 'అమావాస్య';
        if (code === 'ta') return 'அமாவாசை';
        if (code === 'bn') return 'অমাবস্যা';
        return 'अमावस्या';
      }
    }
    return dict[tithiNum];
  }
  return fallbackName;
}
